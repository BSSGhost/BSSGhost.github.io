import 'dotenv/config';
import mysql from 'mysql2/promise';
import { getDbSslConfig } from './db-ssl.js';
const ssl = await getDbSslConfig();
const c = await mysql.createConnection({ host: process.env.DB_HOST, port: Number(process.env.DB_PORT || 3306), user: process.env.DB_USER, password: process.env.DB_PASSWORD || '', database: process.env.DB_NAME, ...(ssl ? { ssl } : {}) });
const [[i]] = await c.query('SELECT DATABASE() AS base, CURRENT_USER() AS compte, VERSION() AS version');
console.log('Hôte :', process.env.DB_HOST);
console.log(i);
const [t] = await c.query('SHOW TABLES');
console.log(t.length, 'tables :', t.map((r) => Object.values(r)[0]).join(', ') || '(aucune)');
await c.end();
